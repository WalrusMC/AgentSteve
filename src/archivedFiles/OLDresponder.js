import OpenAI from "openai";
import { createNewPlugin, editPlugin, retrievePluginCode, pluginCrashReport } from "../tools/plugin.js";
import { sendMsgDiscord } from "../tools/sendMsgDiscord.js";
import { getPastChats } from "../utils/getPastChats.js";
import fs from "fs/promises";
import { createLogger } from "../utils/logger.js";
const client = new OpenAI;
const log = createLogger("responder");

const systemPrompt = `You are Steve, an advanced multi-model AI assistant for Minecraft server owners.
You live on Discord and help users with:
- Writing and editing Minecraft Paper plugins
- Code generation
- Minecraft server configuration
- Running console commands
- Manipulating Minecraft server files (upload/edit/delete/etc)
- Understanding logs
- Troubleshooting

Rules:
- Always answer the user’s CURRENT MESSAGE, not assumptions or past intents.
- Keep answers clear and actionable.
- Be concise by default (1–4 short paragraphs). Expand only if the user asks.
- If the user asks to create or edit a plugin, you must use tools — not free-text.
- If a tool call is necessary to complete the task, do not answer directly. Call the tool.
- If unsure which plugin the user means, ask for clarification via respond(), not assumptions.
`;

const developerPrompt = `
Your job is to analyze the CURRENT USER MESSAGE and decide the correct sequence of actions using your available tools/functions.
You must:

1. Determine the user’s intent
Classify each request as exactly one of:
- Create a new plugin
- Edit an existing plugin
- General question (no function needed)

2. If the task requires plugin modification or creation
You must follow one of these workflows:
A. Edit existing plugin workflow:
- Call retrievePluginCode .
- Construct clear deletions and insertions arrays based on the requested change.
- Call editPlugin
- Respond to the user and send the JAR generated by the editPlugin function
B. Creating a new plugin workflow:
- Call createNewPlugin
- Respond to the user and send the JAR generated by the createNewPlugin function

4. When unsure what to modify
- Request clarification via respond(), never assume.

5. Your answer will be sent on Discord, so you may use formatting (bold, italics, code blocks, emoji).
`;

/**
 * Sends the user message and context to the selected model and executes any tool calls.
 * Falls back to Discord response on errors.
 */
export async function responder(model, message, summary, assistantMessage = "", extraDeveloperMessage = "", overrideDevMessage = false) {
  log.info(`Responder running with model: ${model}`);

  // User input and past chats
  const pastChats = await getPastChats(message);
  const attachmentNames = message?.attachments?.size 
  ? Array.from(message.attachments.values()).map(a => a.name).join(",")
  : "";
  const userInput = `(PAST CHATS)\n${pastChats}\n(CURRENT USER MESSAGE)UTC_TIME:${message.createdAt.toISOString()}|ROLE:ADMINISTRATOR|USERNMAME:${message.author.username}|USER_ID:${message.author.id}|CHAT:${message.content}${attachmentNames ? `|ATTACHMENTS:${attachmentNames}` : ""}\n`;

  // Files
  const files = JSON.parse(await fs.readFile(`./db/${message.guildId}/files.json`, "utf-8"));
  const fileNames = Object.keys(files);
  let developerFiles = fileNames.length ? "\n\n(FILES YOU HAVE ACCESS TO)\n" : "";
  for (const fileName of fileNames) {
    developerFiles += `${fileName}: ${files[fileName]}\n`;
  }

  // Plugins + versions the model can reference quickly
  let pluginRegistry = {};
  try {
    pluginRegistry = JSON.parse(await fs.readFile(`./db/${message.guildId}/plugins.json`, "utf-8"));
  } catch {
    pluginRegistry = {};
  }
  const pluginEntries = Object.entries(pluginRegistry);
  let developerPlugins = pluginEntries.length ? "\n\n(MINECRAFT PLUGINS YOU HAVE ACCESS TO)\n" : "";
  for (const [pluginName, version] of pluginEntries) {
    developerPlugins += `${pluginName}${version ? ` (v${version})` : ""}\n`;
  }

  // Tools
  const tools = [
    { type: "web_search" },
    {
      type: "function",
      name: "createNewPlugin",
      description: "Creates a brand new Paper 1.20.1 plugin and builds a JAR. This tool is for brand new plugins. Do not call if editing an existing plugin",
      parameters: {
        type: "object",
        properties: {
          pluginName: { 
            type: "string", 
            description: "Name of the plugin. Must be a valid Java class name. This becomes the main class filename, the jar filename, the pom.xml artifactId, and the GitHub repo name.",
          },
          pluginJava: { 
            type: "string", 
            description: "The plugin's code. The correct package is: com.walrusmc. ",
          },
          pluginYML: { 
            type: "string", 
            description: "The plugin.yml.",
          },
          configYML: { 
            type: "string", 
            description: "Optional. The config.yml.",
          },
          dependencies: { 
            type: "array", 
            description: `Optional. Additional Maven dependency XML blocks to insert inside pom.xml <dependencies> 
            (as raw XML). DO NOT include paper-api (1.20.1) or adventure-api (these are already included), but include any other dependencies your code requires. Example format:
            <dependency>
              <groupId>com.github.placeholderapi</groupId>
              <artifactId>placeholderapi</artifactId>
              <version>2.11.5</version>
              <scope>provided</scope>
            </dependency>`, 
            items: { type: "string", description: "A single Maven <dependency>...</dependency> XML block as raw text."},
          },
          noteToSelf: { 
            type: "string",
            description: `Optional. Information on why it was neccessary to call the tool and insructions to yourself on what to do next.`,
          },
        },
        required: ["pluginName", "pluginJava", "pluginYML"],
      },
    },
    {
      type: "function",
      name: "retrievePluginCode",
      description: "Retrieve code from a plugin. Use this BEFORE editing if you do not already have all the code you need. Do not guess code.",
      parameters: {
        type: "object",
        properties: {
          pluginName: {
            type: "string",
            description: "The name of the plugin to retrieve",
            enum: Object.keys(pluginRegistry),
          },
          files: {
            type: "array",
            description: "The code files to retrieve.",
            items: { type: "string", enum: ["pluginJava", "pluginYML", "configYML"]},
          },
        },
        required: ["pluginName", "files"],
      },
    },
    {
      type: "function",
      name: "editPlugin",
      description: "Makes changes to a plugin via deletions and insertions and then generates a new plugin JAR. All plugin edits MUST happen using this tool. You may call retrievePluginCode first if needed.",
      parameters: {
        type: "object",
        properties: {
          pluginName: {
            type: "string",
            description: "The name of the plugin to edit",
            enum: Object.keys(pluginRegistry),
          },
          deletions: {
            type: "array",
            description: "An array of sections of the code to delete",
            items: { 
              type: "object",
              description: "A specific section of code to delete",
              properties: {
                file: { type: "string", description: "The target file", enum: ["pluginJava", "pluginYML", "configYML"] },
                startLine: { type: "integer", description: "The first line to be deleted" },
                endLine: { type: "integer", description: "The last line to be deleted" },
              },
              required: ["file", "startLine", "endLine"],
             },
          },
          insertions: {
            type: "array",
            description: "An array of sections of code to insert",
            items: {
              type: "object",
              description: "A specific section of code to insert",
              properties: {
                file: { type: "string", description: "The target file", enum: ["pluginJava", "pluginYML", "configYML"] },
                startLine: { type: "integer", description: "The line to insert code after" },
                content: { type: "string", description: "The code to be inserted" },
              },
              required: ["file", "startLine", "content"],
            },
          },
          addDependencies: {
            type: "array",
            description: `New Maven dependency XML blocks to insert inside pom.xml <dependencies> 
            (as raw XML). Example format:
            <dependency>
              <groupId>com.github.placeholderapi</groupId>
              <artifactId>placeholderapi</artifactId>
              <version>2.11.5</version>
              <scope>provided</scope>
            </dependency>`,
            items: { type: "string", description: "The specific Maven dependency block to add." },
          },
          removeDependencies: {
            type: "array",
            description: "An array of dependencies to remove",
            items: { type: "integer", description: "The specific dependency to remove" },
          },
        },
        required: ["pluginName"],
      },
    },
    {
      type: "function",
      name: "respond",
      description: "Respond to the user message. Use this after completing tool workflows or when user clarification is required.",
      parameters: {
        type: "object",
        properties: {
          responseText: {
            type: "string",
            description: "The textual response that will be sent to the user.",
          },
          files: {
            type: "array",
            description: "Optional. An array of the names of all files to send.",
            items: { 
              type: "string",
              enum: fileNames,
              description: "The name of the file you wish to send."
            },
          },
        },
        required: ["responseText"],
      },
    },
  ]

  // Send request to OpenAI API
  log.response("OPENAI INPUT (RESPONDER)", `|SYSTEM|\n${systemPrompt}\n|DEVELOPER|\n${overrideDevMessage ? overrideDevMessage : developerPrompt + developerFiles + developerPlugins + extraDeveloperMessage}\n|USER|\n${userInput}\n|ASSISTANT|\n(MEMORY SUMMARY)\n${summary}\n\n${assistantMessage}`);
  const response = await client.responses.create({
    model: model,
    input: [
      { role: "system", content: systemPrompt },
      { role: "developer", content: overrideDevMessage ? overrideDevMessage : `${developerPrompt}${developerFiles}${developerPlugins}${extraDeveloperMessage}` },
      { role: "user", content: userInput },
      { role: "assistant", content: `(MEMORY SUMMARY)\n${summary}\n\n${assistantMessage}` },
    ],
    tools: tools
  });
  log.response("RESPONDER RESPONSE", response);

  // Call tools
  const toolCall = response.output.find?.(c => c.type === "function_call" || c.type === "tool_call");
  if (toolCall) {
    const args = JSON.parse(toolCall.arguments);
    let result;
    switch (toolCall.name) {
      case "createNewPlugin":
        if (Object.keys(pluginRegistry).includes(args.pluginName)) {
          const codeDump = await retrievePluginCode(args.pluginName, args.files, message.guildId);
          const ovrdDevMsg = `${developerPrompt}\n(RECENT INFORMATION)\nIn order to answer the CURRENT USER MESSAGE, you decided to create a new plugin with the name of a plugin that already exists. If you want to create a new plugin, you must create your plugin with a new name. If you want to edit a pre-existing plugin, you must use the editPlugin tool.\nHere is the pre-existing plugin's code:\n${codeDump}`;
          return await responder(model, message, summary, assistantMessage, extraDeveloperMessage, ovrdDevMsg);
        }
        result = await createNewPlugin(args.pluginName, args.pluginJava, args.pluginYML, args?.configYML, args?.dependencies, message.guildId);
        if (result.success) {
          files[result.file] = "A Minecraft plugin JAR.";
          await fs.writeFile(`./db/${message.guildId}/files.json`, JSON.stringify(files, null, 2));
          return await responder(model, message, summary, args.noteToSelf ? `(NOTE TO SELF)\n${args.noteToSelf}` : "", `(RECENT INFORMATION)
            You just chose to call the createNewPlugin tool in order to answer the CURRENT USER MESSAGE and a plugin JAR has been generated for you: ${result.file}\n\n` );
        } else {
          const ovrdDevMsg = `${developerPrompt}\n(RECENT INFORMATION)\nIn order to answer the CURRENT USER MESSAGE, you just tried to create a new plugin.\nMaven crashed while trying to build your plugin into a JAR. You may call the editPlugin tool to fix the plugin.\n${pluginCrashReport(result.name, result.version, result.code, result.error)}`;
          return await responder(model, message, summary, assistantMessage, extraDeveloperMessage, ovrdDevMsg);
        }
      case "editPlugin":
        result = await editPlugin(args.pluginName, args.deletions, args.insertions, args.addDependencies, args.removeDependencies, message.guildId);
        if (result.success) {
          files[result.file] = "A Minecraft plugin JAR.";
          await fs.writeFile(`./db/${message.guildId}/files.json`, JSON.stringify(files, null, 2));
          return await responder(model, message, summary, args.noteToSelf ? `(NOTE TO SELF)\n${args.noteToSelf}` : "", `(RECENT INFORMATION)\n
            You just chose to call the editPlugin tool in order to answer the CURRENT USER MESSAGE and a plugin JAR has been generated for you: ${result.file}\n\n` );
        } else {
          const ovrdDevMsg = `${developerPrompt}\n(RECENT INFORMATION)\nIn order to answer the CURRENT USER MESSAGE, you just tried to edit a plugin.\nMaven crashed while trying to build your plugin into a JAR. You may call the editPlugin tool again to fix the plugin.\n${pluginCrashReport(result.name, result.version, result.code, result.error)}`;
          return await responder(model, message, summary, assistantMessage, extraDeveloperMessage, ovrdDevMsg);
        }
      case "retrievePluginCode": {
        const codeDump = await retrievePluginCode(args.pluginName, args.files, message.guildId);
        const ovrdDevMsg = `${developerPrompt}\n(RECENT INFORMATION)\nIn order to answer the CURRENT USER MESSAGE, you called the retrievePluginCode tool.\nHere is the code you requested:\n${codeDump}`;
        return await responder(model, message, summary, assistantMessage, extraDeveloperMessage, ovrdDevMsg);
      }
      case "respond":
        return await sendMsgDiscord(args.responseText, message, args.files);
      default:
        log.error("GPT did not call a valid tool.");
        return await sendMsgDiscord("Oh no! An error has occured.", message);
    }

  } else {
    log.error("GPT did not call a tool!");
    return await sendMsgDiscord("Oh no! An error has occured.", message);
  }
};
